<script lang="ts">
  import { app } from '$lib/state/app.svelte';
  import { blip, requestNotificationPermission } from '$lib/util/notify';

  const s = $derived(app.settings);
  let permission = $state<NotificationPermission | 'unsupported'>(typeof Notification === 'undefined' ? 'unsupported' : Notification.permission);

  async function enableDesktop(on: boolean) {
    if (on && permission !== 'granted' && permission !== 'unsupported') {
      permission = await requestNotificationPermission();
      if (permission !== 'granted') {
        app.toast('Your browser blocked notifications — allow them in the site settings', 'error');
        return;
      }
    }
    await app.updateSettings({ desktopNotifications: on });
  }
</script>

<h2>Notifications</h2>
<p class="muted">Notifications are generated by this tab — there's no push service involved, so nothing about your messages goes to Google or Apple.</p>

<label class="srow">
  <span class="txt">
    <strong>Desktop notifications</strong>
    <small>
      {#if permission === 'unsupported'}Your browser doesn't support them.{:else if permission === 'denied'}Blocked in your browser's site settings.{:else}For DMs and mentions while this window isn't focused.{/if}
    </small>
  </span>
  <input type="checkbox" class="switch" checked={s.desktopNotifications && permission === 'granted'} disabled={permission === 'unsupported' || permission === 'denied'} onchange={(e) => enableDesktop((e.target as HTMLInputElement).checked)} />
</label>
<label class="srow">
  <span class="txt"><strong>Sounds</strong><small>A soft blip for DMs and mentions</small></span>
  <button class="btn small ghost" onclick={() => blip()}>Test</button>
  <input type="checkbox" class="switch" checked={s.notificationSounds} onchange={(e) => app.updateSettings({ notificationSounds: (e.target as HTMLInputElement).checked })} />
</label>

<h3>"While you were away"</h3>
<div class="field">
  <label for="hl">Highlight the most-reacted messages when you come back after at least this many unread messages</label>
  <input id="hl" class="input" type="number" min="10" max="1000" value={s.highlightsThreshold} onchange={(e) => app.updateSettings({ highlightsThreshold: Math.min(1000, Math.max(10, Number((e.target as HTMLInputElement).value) || 30)) })} />
</div>

